export function getLocalizedCategory(cat, lang = "en") {
  if (!cat) return null;
  const tr = cat.translations?.[lang];
  if (!tr) return cat;
  return {
    ...cat,
    name: tr.name || cat.name,
    description: tr.description || cat.description,
    items: tr.items || cat.items,
  };
}

export function getLocalizedProduct(product, lang = "en") {
  if (!product) return null;
  const tr = product.translations?.[lang] || EXTRA_PRODUCT_TRANSLATIONS[product.slug]?.[lang];
  const catObj = PRODUCT_CATEGORIES.find((c) => c.slug === product.categorySlug);
  const localizedCatName = catObj ? getLocalizedCategory(catObj, lang).name : product.category;
  return {
    ...product,
    name: tr?.name || product.name,
    description: tr?.description || product.description,
    categoryDisplay: localizedCatName,
  };
}

